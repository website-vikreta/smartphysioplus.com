// Usage: pnpm content-todo  ->  writes CONTENT_TODO.md listing every TODO-CONFIRM in src/ and P1 review states.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { homeVisit } from "../src/content/homeVisit.ts";
import { flags } from "../src/content/flags.ts";
import { allPages, reviewState } from "../src/lib/content.ts";
import { allResources } from "../src/lib/resources.ts";

const root = new URL("..", import.meta.url).pathname.replace(
  /^\/([A-Za-z]:)/,
  "$1",
);
const items = [];

const walk = (dir) => {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else if (/\.(tsx?|css|mdx)$/.test(name)) {
      readFileSync(p, "utf8")
        .split(/\r?\n/)
        .forEach((line, i) => {
          // Only real comments that start with the marker, not prose that mentions it.
          const m = line.match(
            /^\s*(?:\/\/|\{?\/\*)\s*TODO-CONFIRM:?\s*(.*?)(?:\*\/\}?)?\s*$/,
          );
          if (m)
            items.push(
              `- \`${relative(root, p).replaceAll("\\", "/")}:${i + 1}\` ${m[1].trim()}`,
            );
        });
    }
  }
};
walk(join(root, "src"));

// P1 items: anything in the MDX collections, the P1 route, or naming a P1 flag.
const P1 =
  /conditions\/|rehabilitation\/|\[slug\]|fractureRehab|frozenShoulder|orthoLocalPage|technologyByCondition/;
// P2 items (promptP2.md): checked first, because P2 paths also contain words like "conditions/".
const P2 =
  /faqs\.ts|reviews\.ts|homeVisit|app\/(conditions|rehabilitation|faqs|reviews|resources|review|physiotherapy-at-home)\/|resources\/|paymentMethods|firstVisitChecklist|reschedulePolicy|patientStories|actions\.ts/;
const isP2 = (i) => P2.test(i);
const p2Review = [
  ...allResources.map(
    (r) =>
      `- \`/resources/${r.slug}/\` ${r.clinicallyReviewed ? "live" : "draft"}`,
  ),
  `- \`/physiotherapy-at-home/\` ${!flags.homeVisits ? "off (flag: homeVisits)" : homeVisit.clinicallyReviewed ? "live" : "draft"}`,
];
const review = allPages.map(
  (p) =>
    `- \`/${p.slug}/\` ${reviewState(p)}${p.flag ? ` (flag: ${p.flag})` : ""}`,
);

const md = `# Content TODO

Generated by \`pnpm content-todo\`. Each item needs client confirmation before its flag in \`src/content/flags.ts\` is switched on.

${items.filter((i) => !isP2(i) && !P1.test(i)).join("\n")}

## P1 confirmations

${items.filter((i) => !isP2(i) && P1.test(i)).join("\n")}

### Clinical review (Dr. Nileema Chaudhary)

A page goes live when its flag (if any) is on and its frontmatter has \`clinicallyReviewed: true\` and a \`reviewedAt\` date. Red-flag boxes and FAQs are part of the review. Run \`pnpm content:review-status\` for the current table.

${review.join("\n")}

## P2 confirmations

${items.filter(isP2).join("\n")}

### Clinical review of P2 pages (Dr. Nileema Chaudhary)

Resource articles and the home-visit page use the same gate. The articles carry a "Stop and get assessed" box that is part of the review.

${p2Review.join("\n")}

## Later ideas

- Replace every placeholder image (see PLACEHOLDERS.md).
- FAQs on P1 pages were written from common patient questions; check them against People-Also-Ask / AnswerSocrates research when it is available.
`;
writeFileSync(join(root, "CONTENT_TODO.md"), md);
console.log(`CONTENT_TODO.md written with ${items.length} items.`);
